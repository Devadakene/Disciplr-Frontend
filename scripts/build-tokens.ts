/**
 * Generates src/styles/tokens.generated.css from design-system/tokens/*.json.
 * Deterministic: sorted keys, LF line endings. Fails on unresolved references.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { generateCssVariables } from '../design-system/src/utils/css-variables'

type Json = Record<string, unknown>

const UNRESOLVED_RE = /\{[A-Za-z0-9_.-]+\}/

function isObject(v: unknown): v is Json {
  return typeof v === 'object' && v !== null && !Array.isArray(v)
}

function deepMerge(target: Json, source: Json): Json {
  for (const [key, value] of Object.entries(source)) {
    const existing = target[key]
    if (isObject(existing) && isObject(value)) deepMerge(existing, value)
    else target[key] = value
  }
  return target
}

export function loadTokens(dir: string): Json {
  const merged: Json = {}
  const files = readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort()
  for (const file of files) {
    deepMerge(merged, JSON.parse(readFileSync(join(dir, file), 'utf8')) as Json)
  }
  return merged
}

function block(vars: Record<string, string>, indent: string): string {
  return Object.entries(vars)
    .map(([name, value]) => `${indent}--${name}: ${value};`)
    .join('\n')
}

interface ShadowLayer {
  offsetX: string
  offsetY: string
  blur: string
  spread: string
  color: string
}

/** generateCssVariables serialises shadow arrays as JSON; turn them into CSS. */
function normalizeShadows(vars: Record<string, string>): Record<string, string> {
  const out: Record<string, string> = {}
  for (const [name, value] of Object.entries(vars)) {
    if (value.startsWith('[{')) {
      const layers = JSON.parse(value) as ShadowLayer[]
      out[name] = layers
        .map((l) => `${l.offsetX} ${l.offsetY} ${l.blur} ${l.spread} ${l.color}`)
        .join(', ')
    } else {
      out[name] = value
    }
  }
  return out
}

export function buildTokensCss(tokens: Json): string {
  const light = normalizeShadows(generateCssVariables(tokens, 'light'))
  const dark = normalizeShadows(generateCssVariables(tokens, 'dark'))

  for (const [mode, vars] of [['light', light], ['dark', dark]] as const) {
    for (const [name, value] of Object.entries(vars)) {
      if (UNRESOLVED_RE.test(value)) {
        throw new Error(`Unresolved token reference in ${mode} variable --${name}: ${value}`)
      }
    }
  }

  const darkOnly: Record<string, string> = {}
  for (const [name, value] of Object.entries(dark)) {
    if (light[name] !== value) darkOnly[name] = value
  }

  const css = [
    '/* AUTO-GENERATED by scripts/build-tokens.ts from design-system/tokens/*.json. DO NOT EDIT. */',
    ':root {',
    block(light, '  '),
    '}',
    '',
    ':root[data-theme="dark"] {',
    block(darkOnly, '  '),
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    '  :root:not([data-theme="light"]) {',
    block(darkOnly, '    '),
    '  }',
    '}',
    '',
  ].join('\n')
  return css.replace(/\r\n/g, '\n')
}

const here = dirname(fileURLToPath(import.meta.url))
if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  const root = resolve(here, '..')
  const out = join(root, 'src/styles/tokens.generated.css')
  mkdirSync(dirname(out), { recursive: true })
  writeFileSync(out, buildTokensCss(loadTokens(join(root, 'design-system/tokens'))), 'utf8')
  console.log(`Wrote ${out}`)
}
